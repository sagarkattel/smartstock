@api.post("/admin/site-categories/test")
def category_test(body: TextBody):
    """Preview categories for a name using the SAVED rule files (before refitting)."""
    import smartstock_core as core
    rules = core.compile_site_rules(app3_rules.read_keywords())
    ov = core.load_overrides(app3_rules.read_overrides())
    staff = 1.0 if core.staff_area_match(body.text, rules) else 0.0
    cats, matched, source = core.site_categories(body.text, staff, rules, ov)
    return {"categories": cats, "matched_keywords": matched, "source": source}


