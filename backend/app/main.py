logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
log = logging.getLogger("smartstock")


def _load_models():
    try:
        store.load_active()
    except Exception:
        log.exception("Model loading failed")


@asynccontextmanager
async def lifespan(_app):
    for w in settings.warnings:
        log.warning(w)
    jobs.recover_after_restart()
    uploads.cleanup_old()
    threading.Thread(target=_load_models, daemon=True).start()   # the API answers /health while models load
    yield


app = FastAPI(title="SmartStock API", version="1.0.0", lifespan=lifespan,
              description="Decision-support forecasts for A to Z Vending. SmartStock recommends; people decide.")
app.add_middleware(CORSMiddleware, allow_origins=settings.cors_origins, allow_credentials=False,
                   allow_methods=["GET", "POST", "PUT", "OPTIONS"], allow_headers=["Authorization", "Content-Type"])


@app.exception_handler(ApiError)
async def _api_error(_req, exc: ApiError):
    return JSONResponse(status_code=exc.status, content={"detail": exc.detail, "code": exc.code})


@app.exception_handler(RequestValidationError)
async def _validation_error(_req, exc: RequestValidationError):
    errs = exc.errors()
    msg = "; ".join(f"{'.'.join(str(x) for x in e.get('loc', [])[1:]) or 'input'}: {e.get('msg')}" for e in errs[:5])
    return JSONResponse(status_code=422, content={"detail": msg or "Invalid input.", "code": "invalid_input"})


@app.exception_handler(Exception)
async def _unexpected(_req, exc: Exception):
    log.exception("Unhandled error")
    return JSONResponse(status_code=500, content={"detail": "Something went wrong on the server.", "code": "server_error"})


@app.middleware("http")
async def _security_headers(request: Request, call_next):
    fc.skip_current_month.set(request.query_params.get("skip_current", "").lower() in ("1", "true"))
    resp = await call_next(request)
    resp.headers.setdefault("X-Content-Type-Options", "nosniff")
    resp.headers.setdefault("X-Frame-Options", "DENY")
    resp.headers.setdefault("Referrer-Policy", "no-referrer")
    resp.headers.setdefault("Cache-Control", "no-store")
    return resp


# "Authorize" button in /docs: paste the token from /auth/login (without the word Bearer)
bearer = HTTPBearer(auto_error=False, description="Paste the token returned by POST /api/v1/auth/login")


def require_user(creds: Optional[HTTPAuthorizationCredentials] = Depends(bearer)) -> dict:
    if creds is None or not creds.credentials:
        return auth.check_header(None)          # raises 401 not_authenticated
    return auth.verify_token(creds.credentials.strip())


# ---------------------------------------------------------------- request bodies
class LoginBody(BaseModel):
    username: str = Field(min_length=1, max_length=100)
    password: str = Field(min_length=1, max_length=200)


class TextBody(BaseModel):
    text: str = Field(min_length=1, max_length=300)


class RecommendBody(BaseModel):
    categories: list[str] = Field(default_factory=list, max_length=20)
    staff_area: bool = False
    text: Optional[str] = Field(default=None, max_length=300)
    top: Optional[int] = Field(default=10, ge=1, le=500)


class ProfileBody(BaseModel):
    display_name: str = Field(min_length=1, max_length=60)
    avatar: Optional[str] = Field(default=None, max_length=20)


class PasswordBody(BaseModel):
    current_password: str = Field(min_length=1, max_length=200)
    new_password: str = Field(min_length=1, max_length=200)


class RetrainBody(BaseModel):
    upload_id: Optional[str] = None
    mode: Literal["quick", "full"] = "full"


class RowsBody(BaseModel):
    rows: list[dict] = Field(max_length=5000)


def Gran():
    return Query("week", pattern="^(week|month)$", description="week or month")


def Hor():
    return Query(None, ge=1, le=12, description="weeks 1-12 or months 1-6 (capped by /meta)")


def SL():
    return Query(None, ge=0.5, le=0.95, description="optional service level override: 0.5-0.95")

