@public.post("/auth/login")
def login(body: LoginBody, request: Request):
    client = request.client.host if request.client else "-"
    return auth.login(body.username, body.password, client)


@public.post("/admin/upload/{ticket}")
async def upload_files(ticket: str, files: list[UploadFile] = File(...)):
    uploads.use_ticket(ticket)
    limit = settings.max_upload_mb * 1024 * 1024
    got = []
    for f in files[:10]:
        data = await f.read(limit + 1)
        got.append((f.filename, data))
    upload_id = uploads.save_files(got)
    return uploads.validate(upload_id)


